export function getRegistryHelpText(): string {
  let text = "🌟 **Полный арсенал кастомизированных инструментов Selin AI** 🌟\n\n";
  CAPABILITIES.forEach((cap, index) => {
    text += `${index + 1}. **${cap.name}**\n`;
    text += `   📝 ${cap.description}\n`;
    if (cap.examples.length > 0) {
      text += `   💡 _Примеры:_ ${cap.examples.join("; ")}\n`;
    }
    text += "\n";
  });
  text += "💬 _Просто напишите или скажите голосом любую задачу своими словами, и Selin AI мгновенно решит её!_";
  return text;
}

